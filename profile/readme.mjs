// Writes README.md from content.mjs. Run it after adding/removing links or projects:
//   node profile/readme.mjs
import { writeFileSync } from 'node:fs';
import { profile, links, work, experience, stack, education, settings } from './content.mjs';
import { sections } from './sections.mjs';
import { BREAKPOINT } from './theme.mjs';
import { PILL_HEIGHT } from './components/basics.mjs';

const base = process.env.README_ASSETS_BASE ?? `https://raw.githubusercontent.com/${settings.repo}/${settings.branch}/`;
const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

// Phones get the compact file; otherwise GitHub's theme picks dark or light.
const picture = (name, alt, size) =>
  `<picture><source media="(max-width: ${BREAKPOINT}px)" srcset="${base}${name}-compact.svg"><source media="(prefers-color-scheme: dark)" srcset="${base}${name}-dark.svg"><img src="${base}${name}-light.svg" alt="${attr(alt)}" ${size} align="top"></picture>`;
const link = (href, inner) => `<a href="${attr(href)}">${inner}</a>`;
const full = (name, alt) => picture(name, alt, 'width="100%"');

const pills = links.map((l) => link(l.href, picture(`link-${l.id}`, l.label, `height="${PILL_HEIGHT}"`))).join('');
const strip = Object.fromEntries(sections().map((s) => [s.id, full(`section-${s.id}`, `${s.index} — ${s.title}`)]));
const linkedin = links.find((l) => l.id === 'linkedin')?.href;
const portfolio = links.find((l) => l.id === 'portfolio')?.href;

const rows = [];
for (let i = 0; i < work.length; i += 2) {
  rows.push(
    work
      .slice(i, i + 2)
      .map((w) => link(w.href, picture(`work-${w.id}`, `${w.title} — ${w.description}`, 'width="50%"')))
      .join(''),
  );
}

const alt = {
  hero: `${profile.name} — ${profile.role}. ${profile.summary}`,
  stack: `Stack — ${stack.groups.map((g) => `${g.label}: ${g.items.join(', ')}`).join('; ')}. Also: ${stack.also.join(', ')}.`,
  experience: `Experience — ${experience.map((j) => `${j.company} (${j.role})`).join(', ')}.`,
  activity: 'GitHub contribution activity for the last year',
  education: `Education — ${education.schools.map((s) => `${s.program}, ${s.school}`).join('; ')}.`,
};

const lines = [
  '<!-- Generated by profile/readme.mjs from profile/content.mjs. The images are built by .github/workflows/profile.yml. -->',
  '<div>',
  `${link(portfolio, full('hero', alt.hero))}<br>`,
  `${pills}<br>`,
  `${strip.stack}<br>`,
  `${full('stack', alt.stack)}<br>`,
  `${strip.experience}<br>`,
  `${link(linkedin, full('experience', alt.experience))}<br>`,
  `${strip.work}<br>`,
  ...rows.map((row) => `${row}<br>`),
  `${strip.activity}<br>`,
  `${full('activity', alt.activity)}<br>`,
  `${strip.education}<br>`,
  `${full('education', alt.education)}<br>`,
  `${full('footer', "Let's talk")}<br>`,
  pills,
  '</div>',
  '',
];

const target = process.argv[2] ?? 'README.md';
writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${target}`);
