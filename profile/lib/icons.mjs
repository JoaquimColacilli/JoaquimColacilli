/** Draws a Lucide icon at (x, y) with the given pixel size. */
export function icon(name, { x, y, size = 24, stroke, width = 1.75, opacity }) {
  const paths = icons[name];
  if (!paths) throw new Error(`Unknown icon "${name}"`);
  const s = size / 24;
  const sw = +(width / s).toFixed(3);
  return `<g transform="translate(${x} ${y}) scale(${+s.toFixed(4)})" stroke="${stroke}" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" fill="none"${opacity != null ? ` opacity="${opacity}"` : ''}>${paths
    .map((d) => `<path d="${d}"/>`)
    .join('')}</g>`;
}
